import axios from 'axios';

/**
 * Centralized Axios instance configured with base URL
 * and an automatic Authorization Bearer token header injection.
 */
const api = axios.create({
  baseURL: import.meta.env.VITE_API_URL || 'http://localhost:5000/api',
  headers: {
    'Content-Type': 'application/json',
  },
});

// Interceptor to attach JWT token stored in sessionStorage (session-scoped to current tab)
api.interceptors.request.use(
  (config) => {
    const token = sessionStorage.getItem('token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

// Interceptor to catch 401s (e.g., token expired)
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response && error.response.status === 401) {
      // Clear token if expired or invalid
      // (Optional: handle automatic redirection in context if needed)
    }
    return Promise.reject(error);
  }
);

export default api;
